"""Reduced-envelope scan for the ordered beta-(2,1) reset candidate.

The script tests the standard principal-growing action inequality for lattice
characters generated by the two surviving unit-beta modes D and C.

It reproduces the explicit obstruction
    K = 7 D - 6 C,
which has beta 1 and a near-zero reduced slope at the eta=1e-5 working point.
The source genealogy action is much larger than the natural beta-1 envelope
at that slope, so the v0.8-style uniform action filter cannot hold.

This is a diagnostic certificate, not outward-rounded interval arithmetic.
"""

import math

x = 0.7860153219449903870
delta = 0.0707369344547055350
s = 0.1410877917171212372
T = 2.0 * delta


def I(beta, z):
    beta = abs(float(beta))
    return math.log(z * beta ** (2.0 / 3.0)) - beta**2 / 3.0 * (
        z**3 - beta ** (-2.0)
    )


def unit_slopes(t):
    z0 = x + t
    return z0 - delta, z0 + delta  # D, C


def lattice_slope(m, n, t):
    beta = m + n
    if beta == 0:
        return None
    zD, zC = unit_slopes(t)
    return (m * zD + n * zC) / beta


def source_action(m, n, t):
    zD, zC = unit_slopes(t)
    return abs(m) * I(1, zD) + abs(n) * I(1, zC)


m, n = 7, -6
beta = m + n
z = abs(lattice_slope(m, n, s))
S = source_action(m, n, s)
N = I(abs(beta), z)

print("working point")
print("x     =", x)
print("delta =", delta)
print("s     =", s)
print("T     =", T)
print()
print("explicit witness K = 7D - 6C")
print("beta           =", beta)
print("reduced slope  =", repr(z))
print("source action  =", repr(S))
print("natural action =", repr(N))
print("action defect  =", repr(S - N))
print()

# Finite scan.  Designated/promoted characters are expressed in the (D,C)
# basis: D=(1,0), C=(0,1), P=(1,1), E=(2,1), Q=(2,0),
# H=(2,-1), P_new=(3,-1), together with conjugates.
designated = {
    (1, 0),
    (0, 1),
    (1, 1),
    (2, 1),
    (2, 0),
    (2, -1),
    (3, -1),
}
designated |= {(-m, -n) for m, n in list(designated)}

best = []
for m in range(-50, 51):
    for n in range(-50, 51):
        if (m, n) == (0, 0) or (m, n) in designated:
            continue
        beta = m + n
        if beta == 0:
            continue
        z = lattice_slope(m, n, s)
        if z is None:
            continue
        z = abs(z)
        turning = abs(beta) ** (-2.0 / 3.0)
        if not (0.0 < z < turning):
            continue
        source = source_action(m, n, s)
        natural = I(abs(beta), z)
        best.append((source - natural, m, n, beta, z, source, natural))

best.sort(reverse=True)
print("top principal-growing non-designated defects at t=s")
for row in best[:15]:
    print(row)
